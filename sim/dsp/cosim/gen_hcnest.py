#!/usr/bin/env python3
"""Co-simulation tests cosim/tests/hcnest_NN.txt: a long host command preempting a busy DSP.

Polygonet's 68020 sends host command $98 (vector P:$30 = JSR, a long interrupt that saves the
registers, runs DO loops and returns with RTI) while the DSP is still working on host command $99
(vector P:$32 = JMP, a fast interrupt into a DO FOREVER loop with subroutine calls, REP and BRKcc).
Here the same shape: $99 starts the job; $98 arrives after N more retires (one test per N, so the
command lands on every instruction of the loop, inside the REP and on the BRK); $9a (JMP to BRA *)
ends the test once both are done. The co-simulation checks the RTL against the ISS at every retire.
"""
import os

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tests")
X0, Y0, X1, Y1, A, B = 0, 1, 2, 3, 4, 5
R0 = 16

def movec_imm(reg, val): return [0x3C1C | reg << 5, val & 0xFFFF]   # MOVE #xxxx,D
def movec_wabs(reg, addr): return [0x3814 | reg << 5, addr]          # MOVE S,X:xxxx
NOP, RTS, RTI, HALT = 0x0000, 0x0006, 0x0007, 0x0BFF
INC_A, CLR_A, SUB_Y0_B = 0x4A22, 0x4A01, 0x4A4D
MOVEM_X0_P_R0 = 0x0208                       # MOVE(M) X0,P:(R0)+
ANDI_MR_FC = 0x1AFC                          # I = 0

def jsr(a): return [0x0130, a]
def jmp(a): return [0x0134, a]

mem = {}
def put(addr, words):
    for i, w in enumerate(words): mem[addr + i] = w

# setup at e000: vectors P:30 = JSR e100, P:32 = JMP e040, P:34 = JMP e0f0; IPR host level 2,
# HCR.HCIE, I = 0, Y0 = 0001 (the loop counter step); then the idle loop at e030
setup = (movec_imm(R0, 0x0030)
         + movec_imm(X0, 0x0130) + [MOVEM_X0_P_R0] + movec_imm(X0, 0xE100) + [MOVEM_X0_P_R0]
         + movec_imm(X0, 0x0134) + [MOVEM_X0_P_R0] + movec_imm(X0, 0xE040) + [MOVEM_X0_P_R0]
         + movec_imm(X0, 0x0134) + [MOVEM_X0_P_R0] + movec_imm(X0, 0xE0F0) + [MOVEM_X0_P_R0]
         + movec_imm(X0, 0xFF00) + movec_wabs(X0, 0xFFDF)
         + movec_imm(X0, 0x0004) + movec_wabs(X0, 0xFFC4)
         + [ANDI_MR_FC] + movec_imm(Y0, 0x0001) + jmp(0xE030))
assert len(setup) <= 0x30
put(0xE000, setup)
put(0xE030, [NOP, 0x0BFE])                   # idle: NOP; BRA e030

# the job (host command $99): B = 6; DO FOREVER { INC A; JSR e060; SUB Y0,B; NOP; BRKEQ; NOP }
put(0xE040, movec_imm(B, 0x0006)
     + [0x0002, 0xE04B - 0xE042 - 1]         # DO FOREVER, LA = e04b
     + [INC_A] + jsr(0xE060) + [SUB_Y0_B, NOP, 0x011A, NOP, NOP]   # e044..e04b; BRKEQ at e049
     + jmp(0xE030))                          # e04c
put(0xE060, [0x0F03, INC_A, NOP, RTS])       # REP #3 INC A; NOP; RTS

# the long command ($98): DO #3 { INC A; NOP }, a DO with a zero count (skipped), RTI
put(0xE100, [0x0E03, 0xE102 - 0xE100 - 1 + 1, INC_A, NOP]   # DO #3, LA = e103 (body e102-e103)
     + movec_imm(X1, 0x0000)                 # e104
     + [0x0400 | X1, 0xE108 - 0xE106 - 1]    # e106: DO X1 (0: skipped to e109)
     + [INC_A, INC_A]                        # e108 (LA), never run
     + [RTI])                                # e109
put(0xE0F0, [HALT])

def prog():
    lines, addrs = [], sorted(mem)
    i = 0
    while i < len(addrs):
        a = addrs[i]; ws = [mem[a]]; i += 1
        while i < len(addrs) and addrs[i] == a + len(ws) and len(ws) < 16:
            ws.append(mem[addrs[i]]); i += 1
        lines.append("P %04x " % a + " ".join("%04x" % w for w in ws))
    return lines

START = 22                                   # setup retired, idle loop running
if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    for n in range(0, 40):
        with open(os.path.join(OUT, "hcnest_%02d.txt" % n), "w") as f:
            f.write("# generated by gen_hcnest.py: $98 %d retires after $99\nMODE 2\nSTEPS 2000\n" % n)
            f.write("\n".join(prog()) + "\n")
            f.write("HW %d 1 99\nHW %d 1 98\nHW %d 1 9a\n" % (START, START + 1 + n, START + 300))
            f.write("EXPECT sp 0000\nEXPECT pc e0f0\n")
    print("wrote 40 tests")
